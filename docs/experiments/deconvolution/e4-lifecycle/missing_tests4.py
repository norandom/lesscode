"""Missing-test report for E4 (deconvolution-loop task 6.7, requirement 8.7): 6.4 survivors (real, closed-assumption) on
either tree, M1, review findings F1 to F7, the two realised 6.5 counterexamples; site on both trees, nearest seed test, the
test that would kill it (described). Inputs (read only): results/e4-survivor-readings.json, the hand-written results/
missing-tests-e4-inputs.json, results/e5-gates.json. Sites checked with `enclosing` from the E3 generator (unchanged).
  missing_tests4.py [--orig ROOT] [--cand ROOT] [--out DIR]"""
import argparse, hashlib, json, sys
from pathlib import Path
sys.path.insert(0, str((HERE := Path(__file__).resolve().parent).parent / "e3-evidence-regeneration"))
from missing_tests import enclosing  # noqa: E402
RUNS, RES, SHELLS = HERE.parents[3] / ".runs", HERE / "results", "src/facdrone/shells/"
KINDS = ("sampled survivor", "hand-written survivor", "review finding", "solver counterexample")
SKIP = ("id", "kind", "function", "original_site", "candidate_site", "title", "replay")

def site(root: Path, module: str, line: int, function: str | None) -> str:  # checks the line is inside `function`
    got = enclosing((root / SHELLS / module).read_bytes().decode("utf-8"), line) if function else None
    if function and got != function.split(".")[-1]:
        raise ValueError(f"{root.name} {module}:{line} is in {got}, not {function}")
    return f"{module}:{line}"

def survivor(ident: str, kind: str, tree: str, r: dict, x: dict, osite: str, csite: str) -> dict:
    return {"id": ident, "kind": kind, "class": r["class"], "tree": tree, "hypothesis": r["hypothesis"], "function": r["function"],
            "original_site": osite, "candidate_site": csite, "difference": r["mutation"], "reason": r["reason"], "input_class":
            r["input_class_never_exercised"], "nearest_seed_test": x["nearest_test"], "killing_test": x["killing_test"]}

def build(readings: dict, inputs: dict, gates: dict, orig: Path, cand: Path) -> list[dict]:
    out = []
    for tree, root, other in (("e4o", orig, cand), ("e4c", cand, orig)):
        for k, r in sorted(readings["survivors"][tree].items(), key=lambda kv: int(kv[0])):
            if r["class"] != "equivalent":
                x = inputs["survivors"][tree][k]
                own = site(root, r["module"], r["line"], r["function"])
                oth = site(other, r["module"], x["other_line"], x.get("other_function", r["function"]))
                out.append(survivor(f"{tree}-m{k}", KINDS[0], tree, r, x, *((own, oth) if tree == "e4o" else (oth, own))))
    for k, x in inputs["hand_written"].items():
        r = readings["hand_written_survivors"][f"e4o-{k}"] | {"function": x["function"]}
        out.append(survivor(k, KINDS[1], "both", r, x, site(orig, x["module"], x["orig_line"], x["function"]),
                            site(cand, x["module"], x["cand_line"], x["function"])))
    for kind, key in ((KINDS[2], "findings"), (KINDS[3], "counterexamples")):
        for x in inputs[key]:
            e = {"id": x["id"], "kind": kind, "class": kind.replace(" ", "_"), "tree": "both", "hypothesis": x["hypothesis"], "function":
                 x["cand_function"] or "module level", "original_site": site(orig, x["module"], x["orig_line"], x["orig_function"]),
                 "candidate_site": site(cand, x["module"], x["cand_line"], x["cand_function"])}
            e.update({k: v for k, v in x.items() if k not in e and not k.endswith(("_line", "_function")) and k != "module"})
            if key == "counterexamples":
                e["replay"] = next(p for p in gates[x["pair"]]["replay"] if p["log"].endswith("-pair.crosshair.txt"))
            out.append(e)
    return out

def render(entries: list[dict], meta: dict) -> str:
    L = ["# Missing-test report, E4 (lifecycle scope): 6.4 survivors, M1, review findings F1 to F7, 6.5 counterexamples", "",
         f"Generated by `missing_tests4.py` on {meta['written']} from `{'`, `'.join(meta['inputs'])}`; sites checked on the frozen original",
         f"(`{meta['orig']}`) and the accepted candidate (`{meta['cand']}`). Readings and test descriptions are hand-written readings, not",
         "measurements; tests are described, not written (the owner's stance: tests belong to the TDD workflow). Counts by class: "
         + ", ".join(f"{k} {v}" for k, v in meta["counts"].items()) + ".", ""]  # noqa: E501
    for kind in KINDS:
        L += [f"## {kind.capitalize()}s", ""]
        for e in (e for e in entries if e["kind"] == kind):
            L += [f"### {e['id']}: `{e['function']}` (original `{e['original_site']}`, candidate `{e['candidate_site']}`)" + (f": {e['title']}" if e.get("title") else ""), ""]
            L += [f"- {k.replace('_', ' ').capitalize()}: {v}" for k, v in e.items() if k not in SKIP and v]
            if p := e.get("replay"):
                o, c = (p[next(k for k in p if k.startswith(s))] for s in ("o_", "c_"))
                L.append(f"- Concrete replay (driver encoding, provenance only): args `{p['args']}`; original `{o}`; candidate `{c}`; differ {str(p['differ']).lower()}")
            L.append("")
    return "\n".join(L)

def main(argv: list[str]) -> int:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    for name, default in (("orig", RUNS / "e2-facdrone" / "source"), ("cand", RUNS / "e4-lifecycle" / "cand-turn3"), ("out", RES)):
        p.add_argument(f"--{name}", type=Path, default=default)
    a, names = p.parse_args(argv), ["e4-survivor-readings.json", "missing-tests-e4-inputs.json", "e5-gates.json"]
    entries = build(*(docs := [json.loads((RES / n).read_text(encoding="utf-8")) for n in names]), a.orig, a.cand)
    counts = {c: sum(e["class"] == c for e in entries) for c in dict.fromkeys(e["class"] for e in entries)}
    meta = {"written": docs[1]["written"], "orig": str(a.orig), "cand": str(a.cand), "inputs": names, "counts": counts,
            "input_sha256": {n: hashlib.sha256((RES / n).read_bytes()).hexdigest() for n in names}}
    (a.out / "missing-tests-e4.json").write_text(json.dumps({"meta": meta, "entries": entries}, indent=1), encoding="utf-8")
    (a.out / "missing-tests-e4.md").write_text(render(entries, meta), encoding="utf-8")
    return print(f"missing_tests4: {len(entries)} entries, {counts} -> {a.out}") or 0

if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
